/**
 * Step types that PR #1076 moved from Data Preprocessing to Train Model
 * (Missing Value Handling, Outlier Handling, Categorical Encoding, Feature
 * Engineering). A node saved before that keeps them in its code, and
 * re-saving the node must keep that code unchanged (68076).
 */
import { describe, it, expect } from "vitest";
import {
  BASE_PYTHON_TEMPLATE,
  MovedStepType,
  PreprocessingConfig,
  createPreprocessingStep,
  generatePythonCodeFromConfig,
  getMovedStepNotice,
  getStepTypeDisplayName,
  isMovedStepType,
  withoutMissingMovedSteps,
} from "@/views/AIAgents/Workflows/nodeDialogs/training/preprocessingConfig";
import {
  generatedSectionMatchesConfig,
  loadPreprocessingConfig,
  sameGeneratedSection,
} from "@/views/AIAgents/Workflows/nodeDialogs/training/preprocessingConfigState";

// The step blocks below are the exact output of the pre-#1076 generator
// (preprocessingConfig.ts at 830dd115^1) for one step of each moved type.
const MOVED_BLOCKS: Record<MovedStepType, string> = {
  missing_value_handling: `    # STEP_START:step_mv:missing_value_handling
    # STEP_CONFIG:{"columns":[{"columnName":"age","strategy":"impute_median"}]}
    # Handle missing values
    if "age" in df.columns:
        df.loc[:, "age"] = df["age"].fillna(df["age"].median())
    # STEP_END:step_mv:missing_value_handling`,
  outlier_handling: `    # STEP_START:step_out:outlier_handling
    # STEP_CONFIG:{"columns":[{"columnName":"income","strategy":"cap_outliers","method":"iqr","iqrMultiplier":1.5}]}
    # Handle outliers
    if "income" in df.columns:
        # Handle outliers in income using IQR method
        Q1 = df["income"].quantile(0.25)
        Q3 = df["income"].quantile(0.75)
        IQR = Q3 - Q1
        lower_bound = Q1 - 1.5 * IQR
        upper_bound = Q3 + 1.5 * IQR
        df.loc[:, "income"] = df["income"].clip(lower=lower_bound, upper=upper_bound)
    # STEP_END:step_out:outlier_handling`,
  categorical_encoding: `    # STEP_START:step_enc:categorical_encoding
    # STEP_CONFIG:{"columns":[{"columnName":"city","strategy":"one_hot","dropFirst":true}]}
    # Encode categorical columns
    if "city" in df.columns:
        # One-hot encode city
        df = pd.get_dummies(df, columns=["city"], prefix="city", drop_first=True)
    # STEP_END:step_enc:categorical_encoding`,
  feature_engineering: `    # STEP_START:step_fe:feature_engineering
    # STEP_CONFIG:{"features":[{"id":"f1","newColumnName":"x_norm","strategy":"normalize","sourceColumns":["x"]}]}
    # Feature engineering
    # Normalize columns: x
    if "x" in df.columns:
        # Check if column is numeric before normalizing
        if pd.api.types.is_numeric_dtype(df["x"]):
            min_val = df["x"].min()
            max_val = df["x"].max()
            if max_val != min_val:
                df["x_norm"] = (df["x"] - min_val) / (max_val - min_val)
    # STEP_END:step_fe:feature_engineering`,
};

const COLUMN_FILTER_BLOCK = `    # STEP_START:step_cf:column_filter
    # STEP_CONFIG:{"selectedColumns":["age","city","income","x"]}
    # Filter columns
    df = df[["age", "city", "income", "x"]]
    # STEP_END:step_cf:column_filter`;

const MOVED_TYPES = Object.keys(MOVED_BLOCKS) as MovedStepType[];

/** A node's pythonCode as the pre-#1076 dialog saved it. */
function legacyNodeCode(blocks: string[]): string {
  return `# Generated Python function template
from typing import Optional

# Store your result in the 'result' variable
# Import any additional libraries you need
# import json
# import requests
# import datetime
import pandas as pd

# DO NOT EDIT THIS FUNCTION
def autogenerated_preprocessing_function(df):
    # Create a copy to avoid SettingWithCopyWarning
    df = df.copy()

${blocks.join("\n\n")}

    return df
def executable_function(params):

    # This is loaded dataframe from file path:
    df = params["df"]
    # Apply the autogenerated preprocessing code
    df = autogenerated_preprocessing_function(df)

    #Write your code here

    return df`;
}

/** What the dialog saves: the steps it read, regenerated into the code. */
function resave(code: string): string {
  const { config } = loadPreprocessingConfig({ pythonCode: code });
  return generatePythonCodeFromConfig(config, code);
}

const LEGACY_ALL = legacyNodeCode([COLUMN_FILTER_BLOCK, ...MOVED_TYPES.map((t) => MOVED_BLOCKS[t])]);

describe("preprocessingConfig - step types moved to Train Model (68076)", () => {
  it.each(MOVED_TYPES)("re-saving a node with a %s step keeps its code unchanged", (type) => {
    const code = legacyNodeCode([MOVED_BLOCKS[type]]);

    const { config } = loadPreprocessingConfig({ pythonCode: code });
    expect(config.steps).toHaveLength(1);
    expect(config.steps[0].type).toBe(type);

    const saved = resave(code);
    expect(saved).toContain(MOVED_BLOCKS[type]);
    expect(saved).not.toContain("# No preprocessing steps configured");
    // The whole generated function is what it was, so it runs the same cleaning.
    expect(sameGeneratedSection(saved, code)).toBe(true);
  });

  it("keeps all four moved steps, in order, around a step the dialog still configures", () => {
    const { config } = loadPreprocessingConfig({ pythonCode: LEGACY_ALL });
    expect(config.steps.map((s) => s.type)).toEqual(["column_filter", ...MOVED_TYPES]);

    const saved = resave(LEGACY_ALL);
    for (const type of MOVED_TYPES) {
      expect(saved).toContain(MOVED_BLOCKS[type]);
    }
    expect(sameGeneratedSection(saved, LEGACY_ALL)).toBe(true);
  });

  it("re-saving again (from the stored steps) still keeps the code", () => {
    const first = resave(LEGACY_ALL);
    const { config } = loadPreprocessingConfig({ pythonCode: LEGACY_ALL });
    // The second open reads the steps stored by the first save.
    const reopened = loadPreprocessingConfig({
      pythonCode: first,
      preprocessingConfig: { ...JSON.parse(JSON.stringify(config)), movedStepsKept: true },
    });
    expect(reopened.source).toBe("stored");
    expect(generatedSectionMatchesConfig(first, reopened.config)).toBe(true);
    expect(generatePythonCodeFromConfig(reopened.config, first)).toBe(first);
  });

  it("adding a new step after a moved one keeps the moved step's code", () => {
    const code = legacyNodeCode([MOVED_BLOCKS.missing_value_handling]);
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    const withNewStep: PreprocessingConfig = {
      steps: [
        ...config.steps,
        { ...createPreprocessingStep("drop_high_null_columns", "step_new") },
      ],
    };

    const saved = generatePythonCodeFromConfig(withNewStep, code);
    expect(saved).toContain(MOVED_BLOCKS.missing_value_handling);
    expect(saved.indexOf("STEP_START:step_mv")).toBeLessThan(saved.indexOf("STEP_START:step_new"));
    expect(saved).toContain("df.isnull().mean() * 100 <= 80");
  });

  it("deleting the moved step removes its code", () => {
    const code = legacyNodeCode([MOVED_BLOCKS.outlier_handling]);
    const saved = generatePythonCodeFromConfig({ steps: [] }, code);
    expect(saved).not.toContain("outlier_handling");
    expect(saved).toContain("# No preprocessing steps configured");
  });

  it("puts back moved steps that an earlier save left out of the stored steps", () => {
    // Re-saved by the buggy dialog: the stored steps lost the moved ones,
    // but the code (not regenerated) still has them.
    const loaded = loadPreprocessingConfig({
      pythonCode: LEGACY_ALL,
      preprocessingConfig: {
        steps: [
          {
            id: "step_cf",
            type: "column_filter",
            enabled: true,
            config: {
              columns: ["age", "city", "income", "x"].map((name) => ({ name, selected: true })),
            },
          },
        ],
      },
    });
    expect(loaded.config.steps.map((s) => s.id)).toEqual([
      "step_cf",
      "step_mv",
      "step_out",
      "step_enc",
      "step_fe",
    ]);
    expect(sameGeneratedSection(generatePythonCodeFromConfig(loaded.config, LEGACY_ALL), LEGACY_ALL)).toBe(true);
  });

  it("a moved step deleted and saved stays deleted on the next open", () => {
    // Saved while the code still had the block (e.g. Save right after Delete).
    const loaded = loadPreprocessingConfig({
      pythonCode: LEGACY_ALL,
      preprocessingConfig: { steps: [], movedStepsKept: true },
    });
    expect(loaded.config.steps).toEqual([]);
  });

  it("takes a moved step's code from the current code, never from stored data", () => {
    // A stored moved step whose code isn't in pythonCode writes nothing, and
    // anything extra in its stored config is ignored - so no code can run
    // that the Code tab doesn't show.
    const stored = {
      steps: [
        {
          id: "step_x",
          type: "missing_value_handling",
          enabled: true,
          config: { rawCode: '\n    import os; os.system("echo hi")\n    ' },
        },
      ],
      movedStepsKept: true,
    } as unknown as PreprocessingConfig;
    const saved = generatePythonCodeFromConfig(stored, BASE_PYTHON_TEMPLATE);
    expect(saved).not.toContain("os.system");
    expect(saved).not.toContain("step_x");
  });

  it("keeps a hand edit made to a moved step's code in the Code tab", () => {
    const code = legacyNodeCode([MOVED_BLOCKS.missing_value_handling]);
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    const edited = code.replace('df["age"].median()', 'df["age"].mean()');

    const saved = generatePythonCodeFromConfig(config, edited);
    expect(saved).toContain('fillna(df["age"].mean())');
    expect(saved).not.toContain("median()");
  });

  it("recognizes moved steps in code with Windows line endings", () => {
    const code = legacyNodeCode([MOVED_BLOCKS.categorical_encoding]).replace(/\n/g, "\r\n");
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    expect(config.steps.map((s) => s.type)).toEqual(["categorical_encoding"]);
    expect(generatePythonCodeFromConfig(config, code)).toContain(
      MOVED_BLOCKS.categorical_encoding.replace(/\n/g, "\r\n").trimStart()
    );
  });

  it("doesn't list a moved step whose code was deleted by hand", () => {
    const { config } = loadPreprocessingConfig({ pythonCode: LEGACY_ALL });
    const handEdited = LEGACY_ALL.replace(MOVED_BLOCKS.outlier_handling, "");
    const loaded = loadPreprocessingConfig({
      pythonCode: handEdited,
      preprocessingConfig: { ...config, movedStepsKept: true },
    });
    expect(loaded.config.steps.map((s) => s.id)).not.toContain("step_out");
    expect(loaded.config.steps.map((s) => s.id)).toContain("step_mv");
  });

  it("a moved step whose code is gone writes nothing and leaves no gap", () => {
    const code = legacyNodeCode([COLUMN_FILTER_BLOCK, MOVED_BLOCKS.missing_value_handling]);
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    const withoutBlock = code.replace(`\n\n${MOVED_BLOCKS.missing_value_handling}`, "");

    expect(withoutMissingMovedSteps(config, withoutBlock).steps.map((s) => s.id)).toEqual([
      "step_cf",
    ]);
    const saved = generatePythonCodeFromConfig(config, withoutBlock);
    expect(saved).not.toContain("missing_value_handling");
    expect(generatedSectionMatchesConfig(saved, withoutMissingMovedSteps(config, saved))).toBe(true);
    expect(sameGeneratedSection(saved, withoutBlock)).toBe(true);
  });

  it("a moved block outside the generated function doesn't count as the step's code", () => {
    const code = legacyNodeCode([MOVED_BLOCKS.outlier_handling]);
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    const moved = code
      .replace(MOVED_BLOCKS.outlier_handling, "")
      .replace("#Write your code here", MOVED_BLOCKS.outlier_handling);
    expect(withoutMissingMovedSteps(config, moved).steps).toEqual([]);
  });

  it("code with Windows line endings keeps its regular steps too", () => {
    const code = legacyNodeCode([COLUMN_FILTER_BLOCK, MOVED_BLOCKS.missing_value_handling]).replace(
      /\n/g,
      "\r\n"
    );
    const { config } = loadPreprocessingConfig({ pythonCode: code });
    expect(config.steps.map((s) => s.type)).toEqual(["column_filter", "missing_value_handling"]);
  });

  it("names each moved step and points to Train Model", () => {
    expect(getMovedStepNotice("missing_value_handling")).toBe(
      "Missing Value Handling moved to Train Model. Configure it there."
    );
    expect(getMovedStepNotice("outlier_handling")).toBe(
      "Outlier Handling moved to Train Model. Configure it there."
    );
    expect(getMovedStepNotice("categorical_encoding")).toBe(
      "Categorical Encoding moved to Train Model. Configure it there."
    );
    expect(getMovedStepNotice("feature_engineering")).toBe(
      "Feature Engineering moved to Train Model. Configure it there."
    );
    expect(getStepTypeDisplayName("missing_value_handling")).toBe("Missing Value Handling");
    expect(isMovedStepType("column_filter")).toBe(false);
  });

  it("a node with no moved steps saves exactly as before", () => {
    const config: PreprocessingConfig = {
      steps: [
        createPreprocessingStep("remove_duplicates", "step_a"),
        createPreprocessingStep("drop_high_null_columns", "step_b"),
      ],
    };
    const code = generatePythonCodeFromConfig(config, BASE_PYTHON_TEMPLATE);
    const { config: parsed } = loadPreprocessingConfig({ pythonCode: code });
    expect(parsed.steps.some((s) => isMovedStepType(s.type))).toBe(false);
    expect(generatePythonCodeFromConfig(parsed, code)).toBe(code);
  });
});
